// Builds the knowledge base: sources/*.{md,txt} -> chunks (<=700 chars, heading-aware, 1-line overlap) -> src/kb.js + evals/kb.json.
// sources/ holds only the public site pages (home EN/ES, book, terms, privacy) from the latest preview build; the street address is replaced.
import fs from "node:fs";
const TITLES = { site_index: "Site: home (EN)", "site_index.es": "Site: home (ES)", site_book: "Site: book a call", site_terms: "Site: terms", site_privacy: "Site: privacy" };
export function chunk(text, max = 700) {
  const lines = text.split(/\n/).map((l) => l.trim()).filter(Boolean), out = [];
  let cur = [], head = "";
  const flush = () => { if (cur.length) out.push((head && cur[0] !== head ? head + "\n" : "") + cur.join("\n")); };
  for (const l of lines) {
    if (/^#{1,4} /.test(l)) { flush(); cur = []; head = l.replace(/^#+ /, ""); cur.push(head); continue; }
    if (cur.join("\n").length + l.length > max && cur.length) { const last = cur[cur.length - 1]; flush(); cur = last.length < 200 ? [last] : []; }
    cur.push(l.length > max ? l.slice(0, max) : l);
  }
  flush();
  return out;
}
const files = fs.readdirSync("sources").sort(), chunks = [];
for (const f of files) {
  const base = f.replace(/\.(md|txt)$/, ""), doc = TITLES[base] || base.replace(/^\d{4}-\d\d-\d\d_/, "").replace(/[_-]/g, " ");
  chunk(fs.readFileSync("sources/" + f, "utf8")).forEach((text, i) => chunks.push({ id: `${base.replace(/[^a-z0-9]+/gi, "-").toLowerCase()}#${i + 1}`, doc, source: "sources/" + f, lang: base.endsWith(".es") ? "es" : "en", text }));
}
fs.writeFileSync("src/kb.js", "// Generated by scripts/ingest.mjs. Do not edit.\nexport const KB = " + JSON.stringify({ built_from: files, chunks }) + ";\n");
fs.writeFileSync("evals/kb.json", JSON.stringify({ built_from: files, n: chunks.length, chunks }, null, 1));
console.log(files.length, "files ->", chunks.length, "chunks");
